DECLARE v_plan uuid := '71878149-378d-477a-a916-6cc4ef01b5c8'; v_hod uuid; r record; n int := 0;
BEGIN
  SELECT locked_by INTO v_hod FROM cmp_plans WHERE id = v_plan;
  -- Every item must stay inside its workstream's current window and finish on or after it starts.
  IF EXISTS (SELECT 1 FROM _cr02 WHERE new_start > new_target OR new_start < old_start OR new_target > old_target) THEN
    RAISE EXCEPTION 'A proposed date falls outside the workstream window or is inverted';
  END IF;
  FOR r IN
    SELECT it.id, c.ws, c.item_code, it.start_date AS cur_start, it.target_date AS cur_target,
           c.old_start AS exp_start, c.old_target AS exp_target, c.new_start AS to_start, c.new_target AS to_target
    FROM _cr02 c
    JOIN cmp_workstreams w ON w.plan_id = v_plan AND w.workstream_code = c.ws
    JOIN cmp_initiatives i ON i.workstream_id = w.id
    JOIN cmp_factors f ON f.initiative_id = i.id
    JOIN cmp_items it ON it.factor_id = f.id AND it.item_code = c.item_code
    ORDER BY c.item_code
  LOOP
    IF r.cur_start IS DISTINCT FROM r.exp_start OR r.cur_target IS DISTINCT FROM r.exp_target THEN
      RAISE EXCEPTION 'Item % % has dates % to %, expected % to %: changed since the proposal, refusing to continue',
        r.ws, r.item_code, r.cur_start, r.cur_target, r.exp_start, r.exp_target;
    END IF;
    UPDATE cmp_items SET start_date = r.to_start, target_date = r.to_target, updated_at = now() WHERE id = r.id;
